import type { Metadata } from 'next';

import { environment } from './env';
import { siteConfig } from './site-config';

/**
 * Page metadata in one shape for every route: title, description, canonical URL, Open Graph
 * and Twitter card (docs/adr/0009-seo-metadata-and-open-graph-images.md).
 *
 * Paths are relative ("/filmes/a-mare"); the root layout's `metadataBase` turns them into
 * absolute URLs.
 *
 * Share images: articles and Duas Leituras entries generate their own (`opengraph-image`
 * files next to the page). Every other page points to the site's card explicitly, because a
 * page that sets `openGraph` no longer inherits the root `opengraph-image`.
 */

/** The site's share card, generated by `src/app/opengraph-image.tsx`. */
const SITE_SHARE_IMAGE = {
  url: '/opengraph-image',
  width: 1200,
  height: 630,
  alt: `${siteConfig.name}: ${siteConfig.tagline}`,
};

/** Absolute URL of a site path, for places where `metadataBase` does not apply. */
export function toAbsoluteUrl(path: string, siteUrl: URL = environment.siteUrl): string {
  return new URL(path, siteUrl).toString();
}

export type ArticleOpenGraph = {
  publishedTime: string;
  modifiedTime: string | null;
  /** Author page paths. */
  authorPaths: string[];
  section: string;
  tags: string[];
};

export type PageMetadataInput = {
  /** Omitted on the home page, which uses the site name alone. */
  title?: string;
  description: string;
  /** The page's own path, used as its canonical URL. */
  path: string;
  article?: ArticleOpenGraph;
  /** True when the route has its own `opengraph-image` file. */
  hasOwnShareImage?: boolean;
  /** Pages that must stay out of search engines (the component preview, for example). */
  isHiddenFromSearchEngines?: boolean;
};

export function buildPageMetadata({
  title,
  description,
  path,
  article,
  hasOwnShareImage = false,
  isHiddenFromSearchEngines = false,
}: PageMetadataInput): Metadata {
  const shareTitle = title ?? siteConfig.name;
  const shareImages = hasOwnShareImage ? {} : { images: [SITE_SHARE_IMAGE] };

  // Next replaces (rather than merges) the layout's `openGraph`, so the shared fields are
  // repeated here on purpose.
  const openGraphBase = {
    title: shareTitle,
    description,
    url: path,
    siteName: siteConfig.name,
    locale: 'pt_BR',
    ...shareImages,
  };

  return {
    ...(title !== undefined && { title }),
    description,
    alternates: { canonical: path },
    openGraph: article
      ? {
          ...openGraphBase,
          type: 'article',
          publishedTime: article.publishedTime,
          ...(article.modifiedTime !== null && { modifiedTime: article.modifiedTime }),
          authors: article.authorPaths.map((authorPath) => toAbsoluteUrl(authorPath)),
          section: article.section,
          tags: article.tags,
        }
      : { ...openGraphBase, type: 'website' },
    twitter: { card: 'summary_large_image', title: shareTitle, description, ...shareImages },
    ...(isHiddenFromSearchEngines && { robots: { index: false, follow: false } }),
  };
}
